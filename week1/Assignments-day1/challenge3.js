//  Challenge 3
//  Find the sum of marks in a given array

// Declaring marks array
let marks = [90, 78, 65, 98];

// Variable to store sum
let sum = 0;

// Looping through array elements
for (let i = 0; i < marks.length; i++) {
  // Adding each element to sum
  sum = sum + marks[i];
}

// Printing total sum
console.log(sum);
